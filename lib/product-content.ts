  /** 스펙 표 (프로그램: 시스템 요구사항 / 서비스: 포함 내역) */
  specsTitle: string;
  specs: SpecRow[];
  /** 진행 일정 (서비스 상품만) */
  timeline?: TimelineStep[];
  /** 상품별 FAQ */
  faqs: ProductFaq[];
  /** 전자상거래법 상품정보제공고시 (소프트웨어 / 서비스 품목) */
